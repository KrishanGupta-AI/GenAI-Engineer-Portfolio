# Interpreted Vs Compiled Language

# Interpreted Language executes line by line and give output respectively.
# If second last line has an error , it still would give an output for all the lines before the error line.

# Compiled Language is the one which gives output of the whole program at once after reading the whole program.
# If even a single line has an error it would not give even a single line output as reads the whole block at once and executes only if it has zero errors.
 

# PRINT : 
print("Hello Krishan")

# VARIABLES  : 
a = 8 
print(a)

# INPUT : 
b = input("Enter a value : ")
print(b)

# OPERATORS : 
c = a + b
print(c)