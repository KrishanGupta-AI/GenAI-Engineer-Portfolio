# AI Vs ML Vs DL

# | Feature           | **AI**                                | **ML**                                 | **DL**                                 |
# | ----------------- | ------------------------------------- | -------------------------------------- | -------------------------------------- |
# | Full form         | Artificial Intelligence               | Machine Learning                       | Deep Learning                          |
# | Meaning           | Machines performing intelligent tasks | Machines learning patterns from data   | ML using multi-layer neural networks   |
# | Scope             | **Broadest**                          | Subset of AI                           | Subset of ML                           |
# | Data dependency   | May or may not need data              | Requires data                          | Usually requires large amounts of data |
# | Human involvement | Rules can be manually defined         | Features often engineered              | Learns features automatically          |
# | Examples          | Chatbot, chess AI, recommendation     | Spam detection, house-price prediction | Image recognition, speech recognition  |
# | Algorithms        | Rule-based systems, ML, DL            | Regression, Trees, SVM, K-Means        | CNN, RNN, LSTM, Transformers           |
# | Common tools      | Varies                                | Scikit-learn                           | PyTorch, TensorFlow                    |


# Simple hierarchy : AI → ML → DL → Transformers → LLMs → Generative AI
# In one line : AI is the goal, ML is a way to achieve AI through learning from data, and DL is ML based on deep neural networks.


# Deep Learning is becoming popular because of :

# Huge amounts of data available for training.
# Powerful GPUs/TPUs enabling faster training.
# Better neural network architectures, especially Transformers.
# Pretrained models that can be reused and fine-tuned.
# Cloud computing making powerful hardware accessible.
# Excellent performance in NLP, computer vision, speech, and Generative AI.

# In short : More data + more computing power + better architectures = rapid growth of Deep Learning and Generative AI.


